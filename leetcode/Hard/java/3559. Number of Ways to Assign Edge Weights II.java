class Solution {
    /** 
     * Константа модуля для вычислений.
     * Используется 10^9 + 7 - стандартный модуль для задач LeetCode.
     */
    private static final int MOD = 1_000_000_007;
    
    /** Список смежности для представления дерева */
    private List<Integer>[] graph;
    
    /** 
     * Таблица двоичных подъёмов для LCA.
     * up[node][i] - вершина, в которую придём из node, поднявшись на 2^i рёбер.
     */
    private int[][] up;
    
    /** 
     * Массив глубин вершин.
     * depth[node] - расстояние от корня дерева до вершины node.
     */
    private int[] depth;
    
    /** 
     * Массив флагов посещения вершин.
     * Используется для обработки возможных несвязных компонент графа.
     */
    private boolean[] visited;
    
    /** Максимальная степень двойки для двоичного подъёма */
    private int LOG;
    
    /**
     * Вычисляет количество способов назначения весов рёбрам для каждого запроса.
     * 
     * <h2>Постановка задачи</h2>
     * <p>Дано дерево с n вершинами. Каждому ребру можно назначить вес 1 или 2.
     * Для каждого запроса [u, v] требуется найти количество способов назначения 
     * весов <b>всем</b> рёбрам дерева, при которых сумма весов на пути между 
     * u и v является чётной.</p>
     * 
     * <h2>Математическое обоснование</h2>
     * <p>Пусть длина пути между u и v равна L (количество рёбер на пути).
     * Для чётной суммы на пути необходимо, чтобы количество рёбер с нечётным 
     * весом (1) на этом пути было чётным.</p>
     * 
     * <p>Из L рёбер пути можно выбрать 0, 2, 4, ... рёбер с весом 1.
     * Количество способов равно:</p>
     * <pre>C(L,0) + C(L,2) + C(L,4) + ... = 2^(L-1) при L > 0</pre>
     * 
     * <p>Рёбра вне пути могут иметь любой вес (1 или 2), но они не влияют 
     * на ответ, так как для каждого запроса считаются все возможные 
     * назначения всех рёбер.</p>
     * 
     * <h2>Алгоритм решения</h2>
     * <ol>
     *   <li>Находим количество вершин n (максимальный индекс + 1)</li>
     *   <li>Строим список смежности дерева</li>
     *   <li>Предвычисляем массив степеней двойки по модулю MOD</li>
     *   <li>Запускаем DFS для нахождения глубин вершин и таблицы LCA</li>
     *   <li>Для каждого запроса находим LCA и вычисляем длину пути</li>
     *   <li>Ответ = pow2[pathLen - 1] для pathLen > 0, иначе 0</li>
     * </ol>
     * 
     * @param edges список рёбер дерева, где edges[i] = [ui, vi]
     * @param queries список запросов, где queries[i] = [ui, vi]
     * @return массив ответов для каждого запроса по модулю 10^9 + 7
     * 
     * @throws IllegalArgumentException если edges или queries равен null
     * 
     * <h2>Пример использования</h2>
     * <pre>{@code
     * Solution sol = new Solution();
     * int[] result = sol.assignEdgeWeights(
     *     new int[][]{{1,2},{1,3},{3,4},{3,5}},
     *     new int[][]{{1,4},{3,4},{2,5}}
     * );
     * // result = [2, 1, 4]
     * // [1,4]: путь 1->3->4 длины 2, ответ = 2^(2-1) = 2
     * // [3,4]: путь 3->4 длины 1, ответ = 2^(1-1) = 1
     * // [2,5]: путь 2->1->3->5 длины 3, ответ = 2^(3-1) = 4
     * }</pre>
     * 
     * <h2>Сложность алгоритма</h2>
     * <ul>
     *   <li>Временная сложность: O((n + q) * log n), 
     *       где n - число вершин, q - число запросов</li>
     *   <li>Пространственная сложность: O(n * log n) для таблицы LCA</li>
     * </ul>
     */
    public int[] assignEdgeWeights(int[][] edges, int[][] queries) {
        // Шаг 1: Определяем количество вершин
        // Индексы могут начинаться с 1 и идти не последовательно
        int n = 0;
        for (int[] edge : edges) {
            n = Math.max(n, Math.max(edge[0] + 1, edge[1] + 1));
        }
        for (int[] query : queries) {
            n = Math.max(n, Math.max(query[0] + 1, query[1] + 1));
        }
        
        // Если нет вершин, возвращаем массив нулей
        if (n == 0) {
            return new int[queries.length];
        }
        
        // Шаг 2: Построение списка смежности
        graph = new ArrayList[n];
        for (int i = 0; i < n; i++) {
            graph[i] = new ArrayList<>();
        }
        
        for (int[] edge : edges) {
            int u = edge[0], v = edge[1];
            graph[u].add(v);
            graph[v].add(u);
        }
        
        // Шаг 3: Предвычисление степеней двойки
        // pow2[i] = 2^i mod MOD
        int[] pow2 = new int[n + 1];
        pow2[0] = 1;
        for (int i = 1; i <= n; i++) {
            pow2[i] = (int)((pow2[i-1] * 2L) % MOD);
        }
        
        // Шаг 4: Инициализация структур для LCA
        LOG = (int)(Math.log(n) / Math.log(2)) + 1;
        up = new int[n][LOG];
        depth = new int[n];
        visited = new boolean[n];
        
        // Запускаем DFS для всех компонент связности
        for (int i = 0; i < n; i++) {
            if (!visited[i]) {
                dfs(i, i);  // Корень компоненты указывает сам на себя
            }
        }
        
        // Шаг 5: Обработка запросов
        int[] results = new int[queries.length];
        for (int i = 0; i < queries.length; i++) {
            int u = queries[i][0], v = queries[i][1];
            
            // Находим наименьшего общего предка
            int l = lca(u, v);
            
            // Вычисляем длину пути: dist(u,l) + dist(v,l)
            int pathLen = depth[u] + depth[v] - 2 * depth[l];
            
            if (pathLen == 0) {
                // Путь нулевой длины - нет рёбер для назначения весов
                results[i] = 0;
            } else {
                // Количество способов = 2^(pathLen-1)
                results[i] = pow2[pathLen - 1];
            }
        }
        
        return results;
    }
    
    /**
     * Рекурсивный обход дерева для вычисления глубин и построения таблицы LCA.
     * 
     * <p>Алгоритм DFS:</p>
     * <ol>
     *   <li>Помечаем вершину как посещённую</li>
     *   <li>Устанавливаем родителя: up[node][0] = parent</li>
     *   <li>Заполняем таблицу двоичных подъёмов для всех степеней:
     *       up[node][i] = up[up[node][i-1]][i-1]</li>
     *   <li>Рекурсивно обходим всех непосещённых соседей,
     *       увеличивая глубину на 1</li>
     * </ol>
     * 
     * @param node текущая вершина
     * @param parent родительская вершина
     */
    private void dfs(int node, int parent) {
        visited[node] = true;
        
        // На 2^0 = 1 ребро вверх находится родитель
        up[node][0] = parent;
        
        // Заполняем таблицу двоичных подъёмов
        // up[node][i] - вершина на 2^i рёбер выше node
        for (int i = 1; i < LOG; i++) {
            up[node][i] = up[up[node][i-1]][i-1];
        }
        
        // Рекурсивно обходим всех непосещённых соседей
        for (int neighbor : graph[node]) {
            if (!visited[neighbor]) {
                depth[neighbor] = depth[node] + 1;
                dfs(neighbor, node);
            }
        }
    }
    
    /**
     * Нахождение наименьшего общего предка (LCA) двух вершин
     * с использованием метода двоичного подъёма.
     * 
     * <p>Алгоритм:</p>
     * <ol>
     *   <li><b>Выравнивание глубин:</b> Поднимаем более глубокую вершину
     *       на разницу глубин, используя двоичное представление разницы</li>
     *   <li><b>Проверка совпадения:</b> Если вершины совпали после 
     *       выравнивания - это LCA</li>
     *   <li><b>Двоичный подъём:</b> Поднимаем обе вершины одновременно,
     *       начиная с наибольшей степени двойки. Если предки на высоте 
     *       2^i различаются - поднимаемся</li>
     *   <li><b>Результат:</b> Родитель любой из вершин является LCA</li>
     * </ol>
     * 
     * <p>Пример работы двоичного подъёма для n=8, LOG=4:</p>
     * <pre>
     * up[node][0] = родитель (на 1 ребро вверх)
     * up[node][1] = дед (на 2 ребра вверх)
     * up[node][2] = прадед (на 4 ребра вверх)
     * up[node][3] = прапрадед (на 8 рёбер вверх)
     * </pre>
     * 
     * @param u первая вершина
     * @param v вторая вершина
     * @return наименьший общий предок вершин u и v
     */
    private int lca(int u, int v) {
        // Шаг 1: Выравниваем глубины - u должна быть не выше v
        if (depth[u] < depth[v]) {
            int temp = u;
            u = v;
            v = temp;
        }
        
        // Поднимаем u на разницу глубин
        // Используем двоичное представление разницы
        int diff = depth[u] - depth[v];
        for (int i = 0; i < LOG; i++) {
            if ((diff & (1 << i)) != 0) {
                u = up[u][i];
            }
        }
        
        // Шаг 2: Если вершины совпали, LCA найден
        if (u == v) {
            return u;
        }
        
        // Шаг 3: Поднимаем обе вершины одновременно
        // Идём от больших степеней к меньшим для точности
        for (int i = LOG - 1; i >= 0; i--) {
            if (up[u][i] != up[v][i]) {
                u = up[u][i];
                v = up[v][i];
            }
        }
        
        // Шаг 4: Родитель u является LCA
        return up[u][0];
    }
}