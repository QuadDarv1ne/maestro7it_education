class Solution:
    def assignEdgeWeights(self, edges: List[List[int]], queries: List[List[int]]) -> List[int]:
        """
        Вычисляет количество способов назначения весов рёбрам для каждого запроса.
        
        Задача: дано дерево с n вершинами. Каждому ребру можно назначить вес 1 или 2.
        Для каждого запроса [u, v] требуется найти количество способов назначения 
        весов ВСЕМ рёбрам дерева, при которых сумма весов на пути между u и v 
        является чётной.
        
        Математическое обоснование:
        - Пусть длина пути между u и v равна L (количество рёбер на пути)
        - Для чётной суммы на пути нужно, чтобы количество рёбер с нечётным весом (1)
          на этом пути было чётным
        - Из L рёбер пути можно выбрать 0, 2, 4, ... рёбер с весом 1
        - Количество способов = C(L,0) + C(L,2) + C(L,4) + ... = 2^(L-1) при L > 0
        - Рёбра вне пути могут иметь любой вес, но они не влияют на ответ,
          так как для каждого запроса считаются все возможные назначения всех рёбер
        - При L = 0 (u = v) нет рёбер для назначения, ответ = 0
        
        Алгоритм:
        1. Находим количество вершин n (максимальный индекс + 1)
        2. Строим список смежности дерева
        3. Предвычисляем массив степеней двойки: pow2[i] = 2^i mod (10^9 + 7)
        4. Запускаем DFS для нахождения глубин вершин и построения LCA
        5. Для каждого запроса находим LCA и вычисляем длину пути
        6. Ответ = pow2[pathLen - 1] для pathLen > 0, иначе 0
        
        Параметры:
            edges (List[List[int]]): Список рёбер дерева, где edges[i] = [ui, vi]
            queries (List[List[int]]): Список запросов, где queries[i] = [ui, vi]
        
        Возвращает:
            List[int]: Массив ответов для каждого запроса по модулю 10^9 + 7
        
        Сложность:
            Временная: O((n + q) * log n), где n - число вершин, q - число запросов
            Пространственная: O(n * log n) для хранения таблицы LCA
        
        Пример:
            >>> solution = Solution()
            >>> solution.assignEdgeWeights(
            ...     [[1,2],[1,3],[3,4],[3,5]], 
            ...     [[1,4],[3,4],[2,5]]
            ... )
            [2, 1, 4]
            
        Пояснение:
            - [1,4]: путь 1->3->4 длины 2, ответ = 2^(2-1) = 2
            - [3,4]: путь 3->4 длины 1, ответ = 2^(1-1) = 1
            - [2,5]: путь 2->1->3->5 длины 3, ответ = 2^(3-1) = 4
        """
        MOD = 10**9 + 7
        
        # Определяем количество вершин как максимальный индекс + 1
        # Индексы могут начинаться с 1 и идти не последовательно
        n = 0
        for u, v in edges:
            n = max(n, u + 1, v + 1)
        for u, v in queries:
            n = max(n, u + 1, v + 1)
        
        # Если нет вершин, возвращаем нули для всех запросов
        if n == 0:
            return [0] * len(queries)
        
        # Построение списка смежности для представления дерева
        graph = [[] for _ in range(n)]
        for u, v in edges:
            graph[u].append(v)
            graph[v].append(u)
        
        # Предвычисление степеней двойки по модулю MOD
        # pow2[i] = 2^i mod MOD
        pow2 = [1] * (n + 1)
        for i in range(1, n + 1):
            pow2[i] = (pow2[i-1] * 2) % MOD
        
        # Подготовка данных для LCA (Lowest Common Ancestor)
        # LOG - максимальная степень двойки для двоичного подъёма
        LOG = n.bit_length()
        
        # up[node][i] - вершина на 2^i рёбер выше node
        up = [[0] * LOG for _ in range(n)]
        
        # depth[node] - глубина вершины (расстояние от корня)
        depth = [0] * n
        
        # visited[node] - флаг посещения (для несвязных графов)
        visited = [False] * n
        
        def dfs(node: int, parent: int) -> None:
            """
            Рекурсивный обход дерева для вычисления глубин и таблицы LCA.
            
            Параметры:
                node (int): Текущая вершина
                parent (int): Родительская вершина
            """
            visited[node] = True
            up[node][0] = parent  # На 2^0 = 1 ребро вверх - родитель
            
            # Заполняем таблицу двоичных подъёмов
            for i in range(1, LOG):
                up[node][i] = up[up[node][i-1]][i-1]
            
            # Рекурсивно обходим всех непосещённых соседей
            for neighbor in graph[node]:
                if not visited[neighbor]:
                    depth[neighbor] = depth[node] + 1
                    dfs(neighbor, node)
        
        # Запускаем DFS для всех компонент связности
        for i in range(n):
            if not visited[i]:
                dfs(i, i)  # Корень компоненты указывает сам на себя
        
        def lca(u: int, v: int) -> int:
            """
            Нахождение наименьшего общего предка (LCA) двух вершин.
            
            Алгоритм:
            1. Выравниваем глубины вершин
            2. Поднимаем обе вершины одновременно до LCA
            
            Параметры:
                u (int): Первая вершина
                v (int): Вторая вершина
            
            Возвращает:
                int: Наименьший общий предок вершин u и v
            """
            # Выравниваем глубины: u должна быть не выше v
            if depth[u] < depth[v]:
                u, v = v, u
            
            # Поднимаем u на разницу глубин
            diff = depth[u] - depth[v]
            for i in range(LOG):
                if diff & (1 << i):
                    u = up[u][i]
            
            # Если вершины совпали, LCA найден
            if u == v:
                return u
            
            # Поднимаем обе вершины одновременно
            for i in range(LOG - 1, -1, -1):
                if up[u][i] != up[v][i]:
                    u = up[u][i]
                    v = up[v][i]
            
            # Родитель u (или v) является LCA
            return up[u][0]
        
        # Обработка запросов
        results = []
        for u, v in queries:
            # Находим наименьшего общего предка
            l = lca(u, v)
            
            # Вычисляем длину пути между вершинами
            # pathLen = dist(u, l) + dist(v, l)
            path_len = depth[u] + depth[v] - 2 * depth[l]
            
            if path_len == 0:
                # Путь нулевой длины - нет рёбер для назначения весов
                results.append(0)
            else:
                # Количество способов = 2^(pathLen-1)
                results.append(pow2[path_len - 1])
        
        return results