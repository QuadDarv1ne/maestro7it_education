class Solution {
    /**
     * Подсчитывает количество «хороших» чисел в диапазоне [1, n].
     * 
     * Хорошее число — это число, которое после поворота каждой цифры на 180°
     * превращается в валидное число, отличное от исходного.
     * 
     * Правила вращения цифр:
     * • 0, 1, 8 → остаются без изменений при вращении
     * • 2 ↔ 5, 6 ↔ 9 → меняются местами при вращении на 180°
     * • 3, 4, 7 → не имеют валидного вращения (число становится невалидным)
     * 
     * Критерии «хорошего» числа:
     * 1. Не содержит цифр 3, 4, 7 (иначе число становится невалидным)
     * 2. Содержит хотя бы одну цифру из {2, 5, 6, 9} 
     *    (иначе после вращения число не изменится)
     * 
     * Алгоритм решения:
     * - Перебираем все числа от 1 до n включительно
     * - Для каждого числа преобразуем его в строку для посимвольной проверки
     * - Проверяем наличие невалидных цифр (3, 4, 7) — если есть, пропускаем
     * - Проверяем наличие «меняющих» цифр (2, 5, 6, 9) — если есть, число «хорошее»
     * - Используем Set для O(1) проверки принадлежности символа
     * 
     * @param n Верхняя граница диапазона [1, n], где 1 ≤ n ≤ 10⁴
     * @return Количество «хороших» чисел в заданном диапазоне
     * 
     * <p><b>Примеры использования:</b></p>
     * <pre>
     *   Solution sol = new Solution();
     *   sol.rotatedDigits(10);   // возвращает 4 (числа: 2, 5, 6, 9)
     *   sol.rotatedDigits(1);    // возвращает 0
     *   sol.rotatedDigits(100);  // возвращает 40
     * </pre>
     * 
     * <p><b>Сложность алгоритма:</b></p>
     * <ul>
     *   <li>Временная: O(n × d), где d — среднее количество цифр в числе 
     *       (для n ≤ 10⁴, d ≤ 5, поэтому решение эффективно)</li>
     *   <li>Пространственная: O(1), используются множества фиксированного размера</li>
     * </ul>
     * 
     * <p><b>Примечание:</b><br>
     * Для очень больших n можно применить Digit DP или комбинаторный подход
     * со сложностью O(log n), но для ограничений LeetCode данное решение
     * является оптимальным по соотношению читаемость/производительность.</p>
     * 
     * @author Дуплей М.И. | Школа программирования Maestro7IT
     * @source <a href="https://school-maestro7it.ru/">https://school-maestro7it.ru/</a>
     */
    public int rotatedDigits(int n) {
        // Множества для быстрой проверки принадлежности символа (O(1))
        Set<Character> invalid = Set.of('3', '4', '7');
        Set<Character> changing = Set.of('2', '5', '6', '9');
        
        int count = 0;  // Счётчик «хороших» чисел
        
        // Перебираем все числа в диапазоне [1, n]
        for (int num = 1; num <= n; num++) {
            String numStr = String.valueOf(num);
            boolean hasInvalid = false;
            boolean hasChanging = false;
            
            // Посимвольная проверка цифр числа
            for (char digit : numStr.toCharArray()) {
                if (invalid.contains(digit)) {
                    hasInvalid = true;
                    break;  // Число невалидно, дальнейшая проверка не нужна
                }
                if (changing.contains(digit)) {
                    hasChanging = true;  // Число изменится после вращения
                }
            }
            
            // Число «хорошее», если не содержит невалидных цифр и изменится
            if (!hasInvalid && hasChanging) {
                count++;
            }
        }
        
        return count;
    }
}