class Solution(object):
    def rotatedDigits(self, n):
        """
        Подсчитывает количество «хороших» чисел в диапазоне [1, n].
        
        Хорошее число — это число, которое после поворота каждой цифры на 180°
        превращается в валидное число, отличное от исходного.
        
        Правила вращения цифр:
        • 0, 1, 8 → остаются без изменений при вращении
        • 2 ↔ 5, 6 ↔ 9 → меняются местами при вращении на 180°
        • 3, 4, 7 → не имеют валидного вращения (число становится невалидным)
        
        Критерии «хорошего» числа:
        1. Не содержит цифр 3, 4, 7 (иначе число становится невалидным)
        2. Содержит хотя бы одну цифру из {2, 5, 6, 9} 
           (иначе после вращения число не изменится)
        
        Алгоритм решения:
        - Перебираем все числа от 1 до n включительно
        - Для каждого числа преобразуем его в строку для посимвольной проверки
        - Проверяем наличие невалидных цифр (3, 4, 7) — если есть, пропускаем
        - Проверяем наличие «меняющих» цифр (2, 5, 6, 9) — если есть, число «хорошее»
        - Используем множества для O(1) проверки принадлежности символа
        
        :type n: int
        :param n: Верхняя граница диапазона [1, n], где 1 ≤ n ≤ 10⁴
        
        :rtype: int
        :return: Количество «хороших» чисел в заданном диапазоне
        
        Примеры:
        >>> sol = Solution()
        >>> sol.rotatedDigits(10)
        4  # Хорошие числа: 2, 5, 6, 9
        
        >>> sol.rotatedDigits(1)
        0  # Нет хороших чисел в диапазоне [1, 1]
        
        >>> sol.rotatedDigits(100)
        40  # 40 чисел удовлетворяют условиям
        
        Сложность алгоритма:
        • Временная: O(n × d), где d — среднее количество цифр в числе 
          (для n ≤ 10⁴, d ≤ 5, поэтому эффективно)
        • Пространственная: O(1), используются множества фиксированного размера
        
        Примечание:
        Для очень больших n можно применить Digit DP или комбинаторный подход
        со сложностью O(log n), но для ограничений LeetCode данное решение
        является оптимальным по соотношению читаемость/производительность.
        
        Автор: Дуплей М.И. | Школа программирования Maestro7IT
        Источник: https://school-maestro7it.ru/
        """
        # Множества для быстрой проверки принадлежности символа (O(1))
        invalid_digits = {'3', '4', '7'}      # Делают число невалидным после вращения
        changing_digits = {'2', '5', '6', '9'}  # Гарантируют изменение числа после вращения
        
        count = 0  # Счётчик «хороших» чисел
        
        # Перебираем все числа в диапазоне [1, n]
        for num in range(1, n + 1):
            num_str = str(num)  # Преобразуем число в строку для итерации по цифрам
            
            # Проверка 1: число не должно содержать невалидных цифр
            if any(digit in invalid_digits for digit in num_str):
                continue  # Пропускаем число, если оно содержит 3, 4 или 7
            
            # Проверка 2: число должно измениться после вращения
            # (содержать хотя бы одну цифру из {2, 5, 6, 9})
            if any(digit in changing_digits for digit in num_str):
                count += 1  # Инкрементируем счётчик «хороших» чисел
        
        return count