class Solution:
    def longestCommonPrefix(self, arr1, arr2):
        """
        Находит длину самого длинного общего префикса среди всех пар (x, y),
        где x из arr1, y из arr2.

        Префикс числа — это число, образованное одной или несколькими его
        начальными цифрами (например, 123 — префикс 12345).

        Алгоритм:
        1. Собрать все возможные префиксы чисел из arr1 в HashSet.
           Префиксы получаются последовательным делением числа на 10.
        2. Для каждого числа из arr2 проверять его префиксы (от самого
           длинного к короткому) на наличие в HashSet.
           При первом совпадении обновить максимальную длину и перейти
           к следующему числу (т.к. более короткие префиксы не дадут
           большей длины).

        Сложность: O((N+M)*L) по времени, O(N*L) по памяти,
        где N = len(arr1), M = len(arr2), L — максимальная длина числа в
        десятичной записи (не более 9 для значений до 10^8).

        Аргументы:
            arr1: Список положительных целых чисел.
            arr2: Список положительных целых чисел.

        Возвращает:
            int: Максимальная длина общего префикса среди всех пар.
        """
        # Шаг 1: собираем все префиксы чисел из arr1
        prefixes = set()
        for x in arr1:
            while x > 0:
                prefixes.add(x)
                x //= 10

        max_len = 0

        # Шаг 2: проверяем префиксы чисел из arr2
        for y in arr2:
            while y > 0:
                if y in prefixes:
                    # Нашли совпадение — обновляем максимум и переходим дальше
                    max_len = max(max_len, len(str(y)))
                    break
                y //= 10

        return max_len